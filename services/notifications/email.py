def send_email_status_sync(to_email: str, subject: str, html: str, settings: Any) -> dict[str, Any]:
    """Best-effort send with a structured receipt for UI/audit feedback."""
    sender_email = _sender_email(settings)
    errors: list[dict[str, str]] = []

    if getattr(settings, "brevo_api_key", ""):
        try:
            req = urllib.request.Request(
                "https://api.brevo.com/v3/smtp/email",
                data=json.dumps(
                    {
                        "sender": {"email": sender_email, "name": "CloudCare"},
                        "to": [{"email": to_email}],
                        "subject": subject,
                        "htmlContent": html,
                    }
                ).encode("utf-8"),
                headers={
                    "api-key": settings.brevo_api_key,
                    "Content-Type": "application/json",
                    "Accept": "application/json",
                },
                method="POST",
            )
            with urllib.request.urlopen(req, timeout=10) as response:
                response.read()
                return {"sent": True, "provider": "brevo", "errors": []}
        except urllib.error.HTTPError as exc:
            detail = exc.read().decode("utf-8")
            print(f"[email] Brevo API error: {exc.code} - {detail}")
            errors.append(_provider_error("brevo", detail))
        except Exception as exc:  # noqa: BLE001 - email is best-effort
            print(f"[email] Brevo API error: {exc}")
            errors.append(_provider_error("brevo", str(exc)))

    if getattr(settings, "resend_api_key", ""):
        try:
            req = urllib.request.Request(
                "https://api.resend.com/emails",
                data=json.dumps(
                    {
                        "from": "CloudCare <onboarding@resend.dev>",
                        "to": to_email,
                        "subject": subject,
                        "html": html,
                    }
                ).encode("utf-8"),
                headers={
                    "Authorization": f"Bearer {settings.resend_api_key}",
                    "Content-Type": "application/json",
                },
                method="POST",
            )
            with urllib.request.urlopen(req, timeout=10) as response:
                response.read()
                return {"sent": True, "provider": "resend", "errors": errors}
        except urllib.error.HTTPError as exc:
            detail = exc.read().decode("utf-8")
            print(f"[email] Resend API error: {exc.code} - {detail}")
            errors.append(_provider_error("resend", detail))
        except Exception as exc:  # noqa: BLE001 - email is best-effort
            print(f"[email] Resend API error: {exc}")
            errors.append(_provider_error("resend", str(exc)))

    if getattr(settings, "smtp_username", "") and getattr(settings, "smtp_password", ""):
        try:
            msg = MIMEMultipart("alternative")
            msg["Subject"] = subject
            msg["From"] = sender_email
            msg["To"] = to_email
            msg.attach(MIMEText(html, "html"))
            with smtplib.SMTP(settings.smtp_host, settings.smtp_port, timeout=10) as server:
                server.starttls()
                server.login(settings.smtp_username, settings.smtp_password)
                server.sendmail(msg["From"], [to_email], msg.as_string())
            return {"sent": True, "provider": "smtp", "errors": errors}
        except Exception as exc:  # noqa: BLE001 - email is best-effort
            print(f"[email] SMTP error: {exc}")
            errors.append(_provider_error("smtp", str(exc)))

    if not errors:
        errors.append(_provider_error("config", "No email provider is configured."))
    return {"sent": False, "provider": None, "errors": errors}


def send_email_sync(to_email: str, subject: str, html: str, settings: Any) -> bool:
    """Best-effort send: Brevo HTTP API -> Resend HTTP API -> raw SMTP."""
    return bool(send_email_status_sync(to_email, subject, html, settings)["sent"])


