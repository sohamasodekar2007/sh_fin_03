"""
Shared email transport and CloudCare notification templates.

The transport prefers Brevo's HTTP API, then falls back to Resend and SMTP so
local demos keep working with the existing environment variables. Template
builders own presentation only; callers decide when a notification is needed.
"""

from __future__ import annotations

