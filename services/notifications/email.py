def _agent_rows(steps: list[dict[str, Any]]) -> str:
    if not steps:
        return f"""<tr><td colspan="4" style="padding:12px;color:{_MUTED};">No agent step details were returned.</td></tr>"""
    rows = []
    for step in steps:
        metrics = ", ".join(f"{m.get('label')}: {m.get('value')}" for m in step.get("metrics") or [])
        rows.append(
            f"""
            <tr>
              <td style="padding:12px;border-top:1px solid {_BORDER};font-weight:700;">{_text(step.get('name'))}</td>
              <td style="padding:12px;border-top:1px solid {_BORDER};">{_text(step.get('status'))}</td>
              <td style="padding:12px;border-top:1px solid {_BORDER};color:{_MUTED};">{_text(step.get('summary'))}</td>
              <td style="padding:12px;border-top:1px solid {_BORDER};color:{_MUTED};">{_text(metrics)}</td>
            </tr>"""
        )
    return "".join(rows)


def _proposal_rows(proposals: list[dict[str, Any]]) -> str:
    if not proposals:
        return f"""<tr><td colspan="5" style="padding:12px;color:{_MUTED};">No action proposals were produced in this run.</td></tr>"""
    rows = []
    for proposal in proposals[:10]:
        rows.append(
            f"""
            <tr>
              <td style="padding:12px;border-top:1px solid {_BORDER};font-weight:700;">{_text(proposal.get('action_type'))}</td>
              <td style="padding:12px;border-top:1px solid {_BORDER};">{_text(proposal.get('status'))}</td>
              <td style="padding:12px;border-top:1px solid {_BORDER};">{_fmt_money(proposal.get('expected_monthly_savings'))}/mo</td>
              <td style="padding:12px;border-top:1px solid {_BORDER};">{_text(proposal.get('risk_level'))}</td>
              <td style="padding:12px;border-top:1px solid {_BORDER};color:{_MUTED};">{_text(proposal.get('rationale_plain_english') or proposal.get('rationale') or proposal.get('resource_arn'))}</td>
            </tr>"""
        )
    return "".join(rows)


