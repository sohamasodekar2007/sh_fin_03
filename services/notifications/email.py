from email.mime.text import MIMEText
from html import escape
from typing import Any


_BRAND = "#2F6690"
_TEXT = "#10222E"
_MUTED = "#627785"
_BORDER = "#E4EBE8"
_BG = "#F7FAF9"
_DANGER = "#B3261E"


def _sender_email(settings: Any) -> str:
    sender = getattr(settings, "smtp_from", "") or ""
    if not sender or "@smtp-brevo.com" in sender or "@" not in sender:
        return "teamalpha817@gmail.com"
    return sender


def _fmt_money(value: Any) -> str:
    try:
        return f"${float(value):,.2f}"
    except (TypeError, ValueError):
        return "$0.00"


def _fmt_pct(value: Any) -> str:
    try:
        return f"{float(value) * 100:.0f}%"
    except (TypeError, ValueError):
        return "0%"


def _text(value: Any, default: str = "-") -> str:
    if value is None or value == "":
        return default
    return escape(str(value))


def _provider_error(provider: str, detail: str) -> dict[str, str]:
    reason = detail
    if provider == "brevo" and "unrecognised IP address" in detail:
        reason = "BREVO_UNAUTHORIZED_IP"
    elif provider == "brevo" and "unauthorized" in detail.lower():
        reason = "BREVO_UNAUTHORIZED"
    elif provider == "smtp" and "Unauthorized IP address" in detail:
        reason = "SMTP_UNAUTHORIZED_IP"
    return {"provider": provider, "reason": reason, "detail": detail}


